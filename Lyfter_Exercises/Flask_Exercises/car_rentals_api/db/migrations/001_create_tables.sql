CREATE TABLE IF NOT EXISTS users(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	full_name VARCHAR(100) NOT NULL,
	username VARCHAR(30) NOT NULL UNIQUE,
	email VARCHAR(80) NOT NULL UNIQUE,
	password VARCHAR(20) NOT NULL,
	birthdate DATE NOT NULL,
	status BOOLEAN NOT NULL DEFAULT true,
	creation_date TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS brands(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS vehicle_models(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(30) NOT NULL,
	brand_id INTEGER NOT NULL REFERENCES brands(id),
	UNIQUE(name, brand_id)
);

CREATE TABLE IF NOT EXISTS vehicles(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	model_id INTEGER NOT NULL REFERENCES vehicle_models(id),
	year INTEGER NOT NULL,
	status VARCHAR(20) NOT NULL CHECK(status IN('Available', 'Rented', 'Maintenance'))
);

CREATE TABLE IF NOT EXISTS rentals(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INTEGER NOT NULL REFERENCES users(id),
	vehicle_id INTEGER NOT NULL REFERENCES vehicles(id),
	rental_date TIMESTAMPTZ NOT NULL DEFAULT now(),
	status VARCHAR(20) NOT NULL CHECK(status IN('Active', 'Completed', 'Cancelled'))
);

CREATE INDEX IF NOT EXISTS ix_vehicle_models_brand_id ON vehicle_models(brand_id);
CREATE INDEX IF NOT EXISTS ix_vehicles_model_id ON vehicles(model_id);
CREATE INDEX IF NOT EXISTS ix_rentals_user_id ON rentals(user_id);
CREATE INDEX IF NOT EXISTS ix_rentals_vehicle_id ON rentals(vehicle_id);

